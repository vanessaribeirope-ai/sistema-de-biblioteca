def boas_vindas():
    print ("Bem vindo ao Sistema de Biblioteca!")

def carregar_livros():
    livros = []
    try:
        with open ("biblioteca.csv", "r", encoding="utf-8") as arquivo:
         for linha in arquivo:
            dados = linha.strip().split(";")
            livros.append(dados)
    except FileNotFoundError:
        pass
    return livros

def salvar_livros(livros):
    with open ("biblioteca.csv","w", encoding = "utf-8") as arquivo:
        for livro in livros:
            linha = ";".join(livro)
            arquivo.write(linha+ "\n")
            print()

