def carregar_livros():
    livros = []
    try:
        with open("biblioteca.csv", "r", encoding="utf-8") as arquivo:
            for linha in arquivo:
                dados = linha.strip().split(";")
                livros.append(dados)
    except FileNotFoundError:
        pass
    return livros

def salvar_livros(livros):
    with open("biblioteca.csv", "w", encoding="utf-8") as arquivo:
        for livro in livros:
            linha = ";".join(livro)
            arquivo.write(linha + "\n")

def cadastrar_pela_interface(titulo, autor, genero, status):
      if not titulo.strip() or not autor.strip():
          return "Preencha o título e o autor!"


      livros = carregar_livros()
      livros.append([titulo, autor, genero, status])
      salvar_livros(livros)

      return "Livro cadastrado com sucesso!"

def listar_pela_interface():
    livros = carregar_livros()

    if not livros:
        return "Nenhum livro cadastrado."

    resultado = ""

    for livro in livros:
        resultado += f"Título: {livro[0]}\n"
        resultado += f"Autor: {livro[1]}\n"
        resultado += f"Gênero: {livro[2]}\n"
        resultado += f"Status: {livro[3]}\n"
        resultado += "--------------------\n"

    return resultado

def pesquisar_pela_interface(titulo):
    livros = carregar_livros()

    for livro in livros:
        if livro[0].strip().lower() == titulo.strip().lower():
            return f"Título: {livro[0]}\nAutor: {livro[1]}\nGênero: {livro[2]}\nStatus: {livro[3]}"

    return "Livro não encontrado."

def emprestar_pela_interface(titulo):
    livros = carregar_livros()

    for livro in livros:
        if livro[0].strip().lower() == titulo.strip().lower():
             if livro[3] == "Emprestado":
                 return "Este livro já está emprestado."

             livro[3] = "Emprestado"
             salvar_livros(livros)
             return "Livro emprestado com sucesso!"

    return "Livro não encontrado."

def devolver_pela_interface(titulo):
    livros = carregar_livros()

    for livro in livros:
        if livro[0].strip().lower() == titulo.strip().lower():
            if livro[3] == "Disponível":
                return "Este livro já está disponível."

            livro[3] = "Disponível"
            salvar_livros(livros)
            return "Livro devolvido com sucesso!"

    return "Livro não encontrado."

def excluir_pela_interface(titulo):
    livros = carregar_livros()

    for livro in livros:
        if livro[0].strip().lower() == titulo.strip().lower():
            livros.remove(livro)
            salvar_livros(livros)
            return "Livro excluído com sucesso!"

    return "Livro não encontrado."

def contar_pela_interface():
    livros = carregar_livros()
    quantidade = 0

    for livro in livros:
        if livro[3] == "Disponível":
            quantidade += 1

    return f"Livros disponíveis: {quantidade}"

import gradio as gr

# Interface Gradio
with gr.Blocks() as interface:
    gr.Markdown("# 📚 Sistema de Biblioteca")

    titulo = gr.Textbox(label="Título do livro")
    autor = gr.Textbox(label="Autor do livro")
    genero = gr.Textbox(label="Gênero do livro")

    status = gr.Dropdown(
        choices = ["Disponível", "Emprestado"],
        label = "Status do livro",
        value = "Disponível"
    )

    botao_cadastrar = gr.Button("📖 Cadastrar livro")
    resultado_cadastro = gr.Textbox(label="Resultado do cadastro", interactive=False)
    botao_cadastrar.click(fn=cadastrar_pela_interface, inputs=[titulo, autor, genero, status], outputs=resultado_cadastro)

    botao_listar = gr.Button("📚 Listar livros")
    resultado_lista = gr.Textbox(label="Resultado da listagem", interactive=False)
    botao_listar.click(fn=listar_pela_interface, inputs=[], outputs=resultado_lista)

    titulo_pesquisa = gr.Textbox(label="Digite o título para pesquisar")
    botao_pesquisar = gr.Button("🔎 Pesquisar livro")
    resultado_pesquisa = gr.Textbox(label="Resultado da pesquisa", interactive=False)
    botao_pesquisar.click(fn=pesquisar_pela_interface, inputs=[titulo_pesquisa], outputs=resultado_pesquisa)

    titulo_emprestimo = gr.Textbox(label="Título do livro para empréstimo")
    resultado_emprestimo = gr.Textbox(label="Resultado do empréstimo", interactive=False)
    botao_emprestar = gr.Button("📖 Emprestar livro")
    botao_emprestar.click(fn=emprestar_pela_interface, inputs=[titulo_emprestimo], outputs=resultado_emprestimo)

    titulo_devolucao = gr.Textbox(label="Título do livro para devolução")
    botao_devolver = gr.Button("↩️ Devolver livro")
    resultado_devolucao = gr.Textbox(label="Resultado da devolução", interactive=False)
    botao_devolver.click(fn=devolver_pela_interface, inputs=[titulo_devolucao], outputs=resultado_devolucao)

